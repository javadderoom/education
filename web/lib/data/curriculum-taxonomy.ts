/**
 * Returns the subject taxonomy or defaults to Grade 4 Fractions.
 */
export function getSubjectTaxonomy(subjectId: string): SubjectTaxonomy {
  if (CANONICAL_TAXONOMIES[subjectId]) {
    return CANONICAL_TAXONOMIES[subjectId];
  }
  // Backward compatibility aliases
  if (subjectId === "SUBJ-MATH5-CH03") return CANONICAL_TAXONOMIES["SUBJ-MATH5-RATIO"];
  if (subjectId === "SUBJ-MATH6-CH04") return CANONICAL_TAXONOMIES["SUBJ-MATH6-COORD"];
  if (subjectId === "SUBJ-MATH4-CH02") return CANONICAL_TAXONOMIES["SUBJ-MATH4-FRACTIONS"];

  const s = (subjectId || "").toUpperCase();
  
  // Grade 5 Routing
  if (s.includes("MATH5-CH01") || (s.includes("MATH5") && (s.includes("CH1") || s.includes("BILLION")))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH01"];
  }
  if (s.includes("MATH5-CH02") || (s.includes("MATH5") && s.includes("CH2"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH02"];
  }
  if (s.includes("MATH5-CH03") || s.includes("RATIO") || s.includes("PERCENT") || (s.includes("MATH5") && s.includes("CH3"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-RATIO"];
  }
  if (s.includes("MATH5-CH04") || (s.includes("MATH5") && s.includes("CH4"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH04"];
  }
  if (s.includes("MATH5-CH05") || (s.includes("MATH5") && s.includes("CH5"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH05"];
  }
  if (s.includes("MATH5-CH06") || (s.includes("MATH5") && s.includes("CH6"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH06"];
  }
  if (s.includes("MATH5-CH07") || (s.includes("MATH5") && s.includes("CH7"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH07"];
  }
  if (s === "5" || s.includes("GRADE5")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH5-CH01"];
  }

  // Grade 6 Routing
  if (s.includes("MATH6-CH01") || (s.includes("MATH6") && (s.includes("CH1") || s.includes("INTEGER")))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH01"];
  }
  if (s.includes("MATH6-CH02") || (s.includes("MATH6") && s.includes("CH2"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH02"];
  }
  if (s.includes("MATH6-CH03") || (s.includes("MATH6") && s.includes("CH3"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH03"];
  }
  if (s.includes("MATH6-CH04") || s.includes("COORD") || (s.includes("MATH6") && s.includes("CH4"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-COORD"];
  }
  if (s.includes("MATH6-CH05") || (s.includes("MATH6") && s.includes("CH5"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH05"];
  }
  if (s.includes("MATH6-CH06") || (s.includes("MATH6") && s.includes("CH6"))) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH06"];
  }
  if (s.includes("MATH6-CH07") || (s.includes("MATH6") && s.includes("CH7")) || s.includes("APPROX")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH07"];
  }
  if (s === "6" || s.includes("GRADE6")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH6-CH01"];
  }

  // Grade 4 Routing
  if (s.includes("CH01") || s.includes("CH1") || s.includes("PATTERN") || s.includes("NUMBER")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-CH01"];
  }
  if (s.includes("CH02") || s.includes("CH2") || s.includes("FRAC")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-FRACTIONS"];
  }
  if (s.includes("CH03") || s.includes("CH3") || s.includes("MULT") || s.includes("DIV")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-CH03"];
  }
  if (s.includes("CH04") || s.includes("CH4") || s.includes("MEASUR") || s.includes("ANGLE")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-CH04"];
  }
  if (s.includes("CH05") || s.includes("CH5") || s.includes("DECIMAL") || s.includes("MIXED")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-CH05"];
  }
  if (s.includes("CH06") || s.includes("CH6") || s.includes("GEOM") || s.includes("SHAPE")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-CH06"];
  }
  if (s.includes("CH07") || s.includes("CH7") || s.includes("STAT") || s.includes("PROB")) {
    return CANONICAL_TAXONOMIES["SUBJ-MATH4-CH07"];
  }

  return CANONICAL_TAXONOMIES["SUBJ-MATH4-FRACTIONS"];
}

/**
 * Helper to get list of all available subjects for the course switcher.
 */
export function getAllAvailableTaxonomies(): SubjectTaxonomy[] {
  return Object.values(CANONICAL_TAXONOMIES);
}

/**
 * Returns all subjects belonging to a specific grade level.
 */
export function getSubjectsByGrade(grade: number): SubjectTaxonomy[] {
  return Object.values(CANONICAL_TAXONOMIES).filter((s) => s.gradeLevel === grade);
}

/**
 * Returns distinct available grade levels in the curriculum.
 */
export function getAvailableGrades(): number[] {
  return Array.from(new Set(Object.values(CANONICAL_TAXONOMIES).map((s) => s.gradeLevel))).sort();
}
